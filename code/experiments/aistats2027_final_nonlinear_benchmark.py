"""Combine the original ten and curvature-audit forty nonlinear toy datasets.

This does not refit estimates. It evaluates the forty saved new estimates on
fresh samples generated by the original test protocol, then summarizes all
fifty paired datasets per true parameter with stratified bootstrap intervals.
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

from aistats2027_nonlinear_transform_experiment import (
    METHODS, THETAS, empirical_energy_distance, forward_transform,
    inverse_transform, sample_asymmetric_mixture,
)


ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'results/nonlinear_transform'
OUT=BASE/'final_benchmark'
BOOTSTRAP=20000


def read_csv(path):
    with path.open(newline='',encoding='utf-8') as handle:
        return list(csv.DictReader(handle))


def write_csv(path,rows):
    with path.open('w',newline='',encoding='utf-8') as handle:
        writer=csv.DictWriter(handle,fieldnames=list(rows[0]))
        writer.writeheader();writer.writerows(rows)


def test_data(theta,seed,d=3,n=512):
    rng=np.random.default_rng(1_000_003+10_007*seed+1_009*THETAS.index(theta))
    reference_train=sample_asymmetric_mixture(rng,n,d)
    source_train=sample_asymmetric_mixture(rng,n,d)
    rng.normal(size=source_train.shape) # Original changed-side noise draw.
    reference_test=sample_asymmetric_mixture(rng,n,d)
    source_test=sample_asymmetric_mixture(rng,n,d)
    rng.normal(size=source_test.shape) # Original held-out noise draw.
    scale=np.maximum(reference_train.std(axis=0,ddof=1),.1)
    return reference_test,forward_transform(source_test,theta),scale


def combine(original,holdout):
    output=[]
    for r in original:
        if int(r['n'])!=512 or float(r['noise_std'])!=0.:
            continue
        output.append(dict(source='original',method=r['method'],theta_true=float(r['theta_true']),
                           seed=int(r['seed']),theta_estimate=float(r['theta_estimate']),
                           parameter_error=float(r['parameter_error']),
                           absolute_parameter_error=float(r['absolute_parameter_error']),
                           corrected_distribution_error=float(r['corrected_distribution_error']),
                           oracle_distribution_error=float(r['oracle_distribution_error']),
                           initial_distribution_error=float(r['initial_distribution_error'])))
    cache={}
    for r in holdout:
        theta=float(r['theta_true']);seed=int(r['seed']);estimate=float(r['theta_estimate'])
        key=(theta,seed)
        if key not in cache:
            reference,observed,scale=test_data(theta,seed)
            reference=reference/scale
            oracle=empirical_energy_distance(reference,inverse_transform(observed,theta)/scale)
            initial=empirical_energy_distance(reference,observed/scale)
            cache[key]=(reference,observed,scale,oracle,initial)
        reference,observed,scale,oracle,initial=cache[key]
        corrected=empirical_energy_distance(reference,inverse_transform(observed,estimate)/scale)
        output.append(dict(source='independent',method=r['method'],theta_true=theta,seed=seed,
                           theta_estimate=estimate,parameter_error=estimate-theta,
                           absolute_parameter_error=abs(estimate-theta),
                           corrected_distribution_error=corrected,
                           oracle_distribution_error=oracle,
                           initial_distribution_error=initial))
    expected={(theta,seed,method) for theta in THETAS for seed in range(50) for method in METHODS}
    seen={(r['theta_true'],r['seed'],r['method']) for r in output}
    if seen!=expected or len(output)!=len(expected):
        raise ValueError(f'Incomplete or duplicate paired benchmark: {len(output)} rows, {len(seen)} keys')
    return output


def bootstrap_indices(n_per_theta,draws=BOOTSTRAP):
    rng=np.random.default_rng(650112)
    return np.concatenate([rng.integers(k*n_per_theta,(k+1)*n_per_theta,
                                           size=(draws,n_per_theta))
                           for k in range(len(THETAS))],axis=1)


def summarize(rows):
    groups=defaultdict(dict)
    for r in rows:
        groups[(r['theta_true'],r['seed'])][r['method']]=r
    units=[groups[key] for key in sorted(groups)]
    indices=bootstrap_indices(50)
    output=[]
    for method in METHODS:
        records=[unit[method] for unit in units]
        errors=np.array([r['parameter_error'] for r in records])
        absolute=np.abs(errors)
        corrected=np.array([r['corrected_distribution_error'] for r in records])
        oracle=np.array([r['oracle_distribution_error'] for r in records])
        initial=np.array([r['initial_distribution_error'] for r in records])
        boot_rmse=np.sqrt(np.mean(errors[indices]**2,axis=1))
        boot_abs=np.mean(absolute[indices],axis=1)
        boot_align=np.mean(corrected[indices],axis=1)
        boot_oracle=np.mean(oracle[indices],axis=1)
        output.append(dict(method=method,replicates_per_theta=50,total_fits=len(records),
                           mean_absolute_parameter_error=float(absolute.mean()),
                           mean_absolute_error_ci_low=float(np.quantile(boot_abs,.025)),
                           mean_absolute_error_ci_high=float(np.quantile(boot_abs,.975)),
                           parameter_rmse=float(np.sqrt(np.mean(errors**2))),
                           parameter_rmse_ci_low=float(np.quantile(boot_rmse,.025)),
                           parameter_rmse_ci_high=float(np.quantile(boot_rmse,.975)),
                           corrected_distribution_error=float(corrected.mean()),
                           corrected_error_ci_low=float(np.quantile(boot_align,.025)),
                           corrected_error_ci_high=float(np.quantile(boot_align,.975)),
                           finite_sample_oracle_error=float(oracle.mean()),
                           oracle_error_ci_low=float(np.quantile(boot_oracle,.025)),
                           oracle_error_ci_high=float(np.quantile(boot_oracle,.975)),
                           uncorrected_distribution_error=float(initial.mean()),
                           excess_over_oracle=float(np.mean(corrected-oracle))))
    comparisons=[]
    energy=[unit['Energy'] for unit in units]
    energy_error=np.array([r['parameter_error'] for r in energy])
    energy_align=np.array([r['corrected_distribution_error'] for r in energy])
    for method in METHODS:
        if method=='Energy':continue
        records=[unit[method] for unit in units]
        errors=np.array([r['parameter_error'] for r in records])
        alignment=np.array([r['corrected_distribution_error'] for r in records])
        rmse_diff=np.sqrt(np.mean(errors[indices]**2,axis=1))-np.sqrt(np.mean(energy_error[indices]**2,axis=1))
        alignment_diff=np.mean((alignment-energy_align)[indices],axis=1)
        comparisons.append(dict(comparator=method,reference='Energy',paired_datasets=len(units),
                                rmse_difference=float(np.sqrt(np.mean(errors**2))-np.sqrt(np.mean(energy_error**2))),
                                rmse_diff_ci_low=float(np.quantile(rmse_diff,.025)),
                                rmse_diff_ci_high=float(np.quantile(rmse_diff,.975)),
                                alignment_difference=float(np.mean(alignment-energy_align)),
                                alignment_diff_ci_low=float(np.quantile(alignment_diff,.025)),
                                alignment_diff_ci_high=float(np.quantile(alignment_diff,.975))))
    theta_rows=[]
    for theta in THETAS:
        for method in METHODS:
            selected=[r for r in rows if r['theta_true']==theta and r['method']==method]
            errors=np.array([r['parameter_error'] for r in selected])
            theta_rows.append(dict(theta_true=theta,method=method,replicates=len(selected),
                                   parameter_rmse=float(np.sqrt(np.mean(errors**2))),
                                   bias=float(errors.mean()),parameter_sd=float(errors.std(ddof=1)),
                                   corrected_distribution_error=float(np.mean([r['corrected_distribution_error'] for r in selected])),
                                   finite_sample_oracle_error=float(np.mean([r['oracle_distribution_error'] for r in selected]))))
    return output,comparisons,theta_rows


def plot(summary):
    colors=['#5384b2','#4d9d79','#a7648f','#d49a51']
    fig,axes=plt.subplots(1,2,figsize=(9.4,3.9),layout='constrained')
    order=[next(row for row in summary if row['method']==method) for method in METHODS]
    xx=np.arange(len(METHODS))
    for ax,metric,low,high,title,ylabel in [
        (axes[0],'parameter_rmse','parameter_rmse_ci_low','parameter_rmse_ci_high',
         'A  Parameter recovery','RMSE ↓'),
        (axes[1],'corrected_distribution_error','corrected_error_ci_low','corrected_error_ci_high',
         'B  Held-out alignment','Common energy distance ↓')]:
        means=np.array([r[metric] for r in order])
        err=np.array([[r[metric]-r[low] for r in order],[r[high]-r[metric] for r in order]])
        ax.bar(xx,means,color=colors)
        ax.errorbar(xx,means,yerr=err,fmt='none',ecolor='black',capsize=3,lw=1)
        ax.set_xticks(xx,METHODS,rotation=18,ha='right')
        ax.set_title(title);ax.set_ylabel(ylabel);ax.grid(axis='y',alpha=.2)
    oracle=order[0]['finite_sample_oracle_error']
    axes[1].axhline(oracle,color='black',ls='--',lw=1,label=f'Oracle correction {oracle:.4f}')
    axes[1].legend(frameon=False,fontsize=8,loc='upper right')
    fig.savefig(OUT/'main_figure.png',dpi=220)
    fig.savefig(OUT/'main_figure.pdf')
    plt.close(fig)


def report(summary,comparisons,theta_rows):
    lines=['# Final nonlinear benchmark: alignment and parameter recovery','',
           'This merges the original 10 seeds with the 40 independent datasets from the curvature audit for **50 paired datasets per true parameter**, at `n=512` and zero changed-side noise. Every estimator sees the same reference and changed samples within a `(theta*, seed)` replicate. New estimates were already frozen in the curvature audit; this script adds the original protocol’s fresh held-out energy-distance evaluation.',
           '', 'Intervals below use 20,000 stratified paired bootstrap draws: within each of the three true-parameter strata, 50 datasets are sampled with replacement, and the same sampled indices are used for every method.',
           '', '| Method | Mean absolute parameter error | Parameter RMSE | Held-out energy distance | Finite-sample oracle |',
           '| --- | ---: | ---: | ---: | ---: |']
    for method in METHODS:
        r=next(x for x in summary if x['method']==method)
        lines.append(f"| {method} | {r['mean_absolute_parameter_error']:.4f} [{r['mean_absolute_error_ci_low']:.4f}, {r['mean_absolute_error_ci_high']:.4f}] | {r['parameter_rmse']:.4f} [{r['parameter_rmse_ci_low']:.4f}, {r['parameter_rmse_ci_high']:.4f}] | {r['corrected_distribution_error']:.5f} [{r['corrected_error_ci_low']:.5f}, {r['corrected_error_ci_high']:.5f}] | {r['finite_sample_oracle_error']:.5f} |")
    lines.extend(['', 'The uncorrected held-out energy distance is '+f"{summary[0]['uncorrected_distribution_error']:.5f}"+'. The oracle applies the known true inverse parameter to each held-out changed sample, so its value is a finite-sample floor rather than zero.',
                  '', '## Paired differences against Energy', '',
                  'Positive RMSE differences favor Energy. The energy-distance differences are comparator minus Energy; all estimates use the same held-out samples.',
                  '', '| Comparator | RMSE difference [95% CI] | Held-out distance difference [95% CI] |',
                  '| --- | ---: | ---: |'])
    for method in [m for m in METHODS if m!='Energy']:
        r=next(x for x in comparisons if x['comparator']==method)
        lines.append(f"| {method} | {r['rmse_difference']:+.4f} [{r['rmse_diff_ci_low']:+.4f}, {r['rmse_diff_ci_high']:+.4f}] | {r['alignment_difference']:+.5f} [{r['alignment_diff_ci_low']:+.5f}, {r['alignment_diff_ci_high']:+.5f}] |")
    lines.extend(['', '## By true parameter', '',
                  '| θ* | Method | RMSE | Bias | SD | Held-out energy | Oracle |',
                  '| ---: | --- | ---: | ---: | ---: | ---: | ---: |'])
    for theta in THETAS:
        for method in METHODS:
            r=next(x for x in theta_rows if x['theta_true']==theta and x['method']==method)
            lines.append(f"| {theta:.1f} | {method} | {r['parameter_rmse']:.4f} | {r['bias']:+.4f} | {r['parameter_sd']:.4f} | {r['corrected_distribution_error']:.5f} | {r['finite_sample_oracle_error']:.5f} |")
    lines.extend(['', '## Interpretation', '',
                  'The common held-out distance lets alignment be compared on one scale. The paired distance differences are small in practical terms; overlapping unpaired intervals alone would not establish equivalence. The oracle column uses the known true parameter, whereas Energy is a fitted estimator.',
                  'This experiment demonstrates the observed phenomenon. The curvature and gradient-noise audit in `../curvature/RESULTS.md` addresses its local estimation mechanism.',
                  '', '## Reproduce', '',
                  '`python scripts/aistats2027_final_nonlinear_benchmark.py` reads the original `runs.csv` and the curvature audit’s `holdout_fits.csv`, evaluates new held-out corrections, and produces all tables and the two-panel PDF/PNG figure in this directory.',
                  ''])
    (OUT/'RESULTS.md').write_text('\n'.join(lines),encoding='utf-8')


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    rows=combine(read_csv(BASE/'runs.csv'),read_csv(BASE/'curvature/holdout_fits.csv'))
    summary,comparisons,theta_rows=summarize(rows)
    write_csv(OUT/'runs.csv',rows)
    write_csv(OUT/'summary.csv',summary)
    write_csv(OUT/'paired_comparisons.csv',comparisons)
    write_csv(OUT/'theta_summary.csv',theta_rows)
    plot(summary)
    report(summary,comparisons,theta_rows)
    (OUT/'metadata.json').write_text(json.dumps(dict(n=512,noise_std=0.,dimension=3,
        original_seeds=list(range(10)),independent_seeds=list(range(10,50)),
        bootstrap_draws=BOOTSTRAP,bootstrap='stratified paired by theta and seed',
        common_evaluation='biased empirical energy distance, n_test=512'),indent=2),encoding='utf-8')


if __name__=='__main__':
    main()
